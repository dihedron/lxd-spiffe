// maxValue is the length beyond which an observation's value is cut in
// the report; the record keeps it whole. Notes are never cut.
const maxValue = 200

// RenderIndex writes the index: the runs, and the gates with their status.
// With links, each gate links to its <gate>.md.
func RenderIndex(w io.Writer, ev *Evidence, reports []GateReport, links bool) error {
	b := &strings.Builder{}
	fmt.Fprintf(b, "# lxd-probe validation report\n\n")
	fmt.Fprintf(b, "Generated by `lxd-probe util report` from %d runs. The report lists the evidence; the decisions are the operator's, recorded with `util note --decision`.\n\n", len(ev.Runs))
	fmt.Fprintf(b, "| Gate | Title | Status | Records | Cells | Decisions | Open items |\n|---|---|---|---|---|---|---|\n")
	for _, r := range reports {
		id := r.Gate.ID
		if links {
			id = fmt.Sprintf("[%s](%s.md)", id, fileName(id))
		}
		fmt.Fprintf(b, "| %s | %s | %s | %d | %d | %d | %d |\n", id, cellText(r.Gate.Title), r.Status, len(r.Records), len(r.Cells), len(r.Decisions), len(r.Open))
	}
	fmt.Fprintf(b, "\n## Runs\n\n")
	for _, run := range ev.Runs {
		fmt.Fprintf(b, "- `%s`\n", run)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// RenderGate writes the report of one gate.
func RenderGate(w io.Writer, r GateReport) error {
	b := &strings.Builder{}
	g := r.Gate
	switch {
	case g.Title != "":
		fmt.Fprintf(b, "# %s — %s\n\n", g.ID, g.Title)
	case g.ID == noGate:
		fmt.Fprintf(b, "# Records without a gate\n\n")
	default:
		fmt.Fprintf(b, "# %s\n\n", g.ID)
	}
	fmt.Fprintf(b, "**Status:** %s. %d records in %d runs.\n\n", r.Status, len(r.Records), len(r.Runs))

	if r.Known {
		fmt.Fprintf(b, "## Question\n\n")
		switch {
		case g.Question != "":
			fmt.Fprintf(b, "%s\n\n", g.Question)
		case g.Withdrawn:
			fmt.Fprintf(b, "Withdrawn: kept for reference stability.\n\n")
		default:
			fmt.Fprintf(b, "%s (the runbook states no separate question).\n\n", g.Title)
		}
	}

	fmt.Fprintf(b, "## Cells covered\n\n")
	if len(r.Cells) == 0 {
		fmt.Fprintf(b, "None.\n\n")
	} else {
		fmt.Fprintf(b, "| Cell | Records | Runs |\n|---|---|---|\n")
		for _, c := range r.Cells {
			fmt.Fprintf(b, "| %s | %d | %d |\n", cellText(cellName(c.Name)), c.Records, c.Runs)
		}
		fmt.Fprintf(b, "\n")
	}
	if len(g.Axes) > 0 {
		var axes []string
		for _, a := range g.Axes {
			axes = append(axes, a.Name+" ("+strings.Join(a.Values, ", ")+")")
		}
		fmt.Fprintf(b, "Relevant axis values: %s. ", strings.Join(axes, "; "))
		if len(r.Missing) == 0 {
			fmt.Fprintf(b, "Each has a real cell.\n\n")
		} else {
			fmt.Fprintf(b, "Without a real cell: %s.\n\n", strings.Join(r.Missing, ", "))
		}
	}

	if r.Known && g.Rules != "" {
		fmt.Fprintf(b, "## Decision rules\n\nFrom the runbook (*Testing → Gate runbooks*); the report does not apply them.\n\n%s\n\n", g.Rules)
	}

	fmt.Fprintf(b, "## Decisions\n\n")
	if len(r.Decisions) == 0 {
		fmt.Fprintf(b, "None recorded.\n\n")
	} else {
		for _, e := range r.Decisions {
			text, _ := value(e.Record, "note.text").(string)
			fmt.Fprintf(b, "- `%s` (%s, %s): %s\n", e.Ref(), e.Time.UTC().Format(time.RFC3339), cellName(e.Cell), inline(text))
		}
		fmt.Fprintf(b, "\n")
	}

	if g.ID == "L10" {
		fmt.Fprintf(b, "## Calls of the attestor's API usage\n\nCounted over every record of the report, through the expectations the records name.\n\n| Purpose | Call | Records |\n|---|---|---|\n")
		for _, c := range r.Calls {
			fmt.Fprintf(b, "| %s | `%s %s` | %d |\n", cellText(c.Purpose), c.Method, c.Path, c.Records)
		}
		fmt.Fprintf(b, "\n")
	}

	fmt.Fprintf(b, "## Open items\n\n")
	if len(r.Open) == 0 {
		fmt.Fprintf(b, "None.\n\n")
	} else {
		for _, o := range r.Open {
			fmt.Fprintf(b, "- %s\n", o)
		}
		fmt.Fprintf(b, "\n")
	}

	fmt.Fprintf(b, "## Observations\n")
	if len(r.Records) == 0 {
		fmt.Fprintf(b, "\nNone.\n")
	}
	run := ""
	for _, e := range r.Records {
		if e.Run != run {
			run = e.Run
			fmt.Fprintf(b, "\n### Run `%s`\n", run)
		}
		renderRecord(b, e)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func renderRecord(b *strings.Builder, e Entry) {
	fmt.Fprintf(b, "\n#### `%s` %s\n\n", e.Ref(), e.Verb)
	fmt.Fprintf(b, "%s · %s · %s", e.Time.UTC().Format(time.RFC3339), cellName(e.Cell), e.Outcome)
	if e.Server != nil {
		fmt.Fprintf(b, " · LXD %s", e.Server.Version)
	}
	if len(e.Expectations) > 0 {
		fmt.Fprintf(b, " · expectations %s", strings.Join(e.Expectations, ", "))
	}
	fmt.Fprintf(b, "\n\n")
	lines := []string{"args: " + strings.Join(e.Args, " ")}
	for _, o := range e.Observations {
		lines = append(lines, o.Key+": "+valueText(o.Key, o.Value))
	}
	fence := strings.Repeat("`", max(3, longestBackticks(lines)+1))
	fmt.Fprintf(b, "%stext\n%s\n%s\n", fence, strings.Join(lines, "\n"), fence)
}

// valueText renders an observation value on one line: strings as they
// are, the rest as compact JSON, cut beyond maxValue except notes.
func valueText(key string, v any) string {
	var s string
	if str, ok := v.(string); ok {
		s = str
	} else {
		data, err := json.Marshal(v)
		if err != nil {
			s = fmt.Sprint(v)
		} else {
			s = string(data)
		}
	}
	s = strings.ReplaceAll(strings.ReplaceAll(s, "\r", `\r`), "\n", `\n`)
	if strings.HasPrefix(key, "note.") || utf8.RuneCountInString(s) <= maxValue {
		return s
	}
	runes := []rune(s)
	return fmt.Sprintf("%s… (%d bytes; see the record)", string(runes[:maxValue]), len(s))
}

func longestBackticks(lines []string) int {
	longest := 0
	for _, l := range lines {
		n := 0
		for _, r := range l {
			if r == '`' {
				n++
				longest = max(longest, n)
			} else {
				n = 0
			}
		}
	}
	return longest
}

// cellText makes text safe in a Markdown table cell.
func cellText(s string) string {
	return strings.ReplaceAll(inline(s), "|", `\|`)
}

// fileName is the report file name of a gate, without .md. A gate comes
// from the records as free text: anything but letters, digits, '-' and
// '_' becomes '_', so that the name stays inside the output directory.
func fileName(id string) string {
	if id == noGate {
		return "no-gate"
	}
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
			return r
		}
		return '_'
	}, id)
}

// Render writes the whole report as one document: the index, then each
// gate.
func Render(w io.Writer, ev *Evidence, reports []GateReport) error {
	if err := RenderIndex(w, ev, reports, false); err != nil {
		return err
	}
	for _, r := range reports {
		if _, err := io.WriteString(w, "\n"); err != nil {
			return err
		}
		if err := RenderGate(w, r); err != nil {
			return err
		}
	}
	return nil
}

// WriteDir writes index.md and one <gate>.md per gate into dir, creating
// it (mode 0700, files 0600, as evidence, PRE-05); existing report files
// are replaced.
func WriteDir(dir string, ev *Evidence, reports []GateReport) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	write := func(name string, render func(io.Writer) error) error {
		b := &strings.Builder{}
		if err := render(b); err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dir, name), []byte(b.String()), 0o600)
	}
	if err := write("index.md", func(w io.Writer) error { return RenderIndex(w, ev, reports, true) }); err != nil {
		return err
	}
	for _, r := range reports {
		if err := write(fileName(r.Gate.ID)+".md", func(w io.Writer) error { return RenderGate(w, r) }); err != nil {
			return err
		}
	}
	return nil
}
